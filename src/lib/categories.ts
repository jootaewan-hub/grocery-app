export function categorize(name: string): Category {
  const text = name.trim()
  const words = text.split(/\s+/)
  // 모든 분류에서 가장 긴 키워드를 고른다(고추장은 '고추'가 아니라 '고추장'). 길이가 같으면 먼저 나온 분류.
  let best: Category = '기타'
  let bestLen = 0
  for (const [category, keywords] of KEYWORDS) {
    for (const kw of keywords) {
      if (kw.length <= bestLen) continue
      // 한 글자 키워드('배', '굴', '파' 등)는 '배달', '굴비'에 걸리지 않게 단어 전체가 같을 때만 쓴다.
      const hit = kw.length === 1 ? words.includes(kw) : text.includes(kw)
      if (hit) {
        best = category
        bestLen = kw.length
      }
    }
  }
  return best
}

